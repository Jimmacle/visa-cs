using System.Runtime.InteropServices;
using System.Text;
using VisaCs.Simulation;
using VisaCs.Usb;

namespace VisaCs.Tests;

/// <summary>
/// Writes docs/attributes.md from live sessions, so the table always matches the code.
/// Runs only when VISACS_GENERATE_DOCS names the output file. Serial and PXI columns need Linux
/// (a pseudo-terminal and a fake sysfs tree); on other systems those columns are left out.
/// </summary>
[Collection(PortlessLanResourceCollection.Name)]
public sealed partial class AttributeTableGenerator
{
    [Fact]
    public void GeneratesAttributeTable()
    {
        var output = Environment.GetEnvironmentVariable("VISACS_GENERATE_DOCS");
        if (string.IsNullOrEmpty(output)) return;

        var columns = new List<(string Title, VisaSession Session)>();
        var cleanup = new List<IDisposable>();
        try
        {
            var sim = new InstrumentSimulator().Start();
            cleanup.Add(sim);
            var lan = new ResourceManager(sim.CreateOptions());
            cleanup.Add(lan);
            columns.Add(("TCPIP INSTR (VXI-11)", lan.Open(sim.Vxi11Resource)));
            columns.Add(("TCPIP INSTR (HiSLIP)", lan.Open(sim.HislipResource)));
            columns.Add(("TCPIP SOCKET", lan.Open(sim.SocketResource)));
            columns.Add(("VICP INSTR", lan.Open(sim.VicpResource)));

            var backend = new SimulatedUsbBackend();
            backend.Devices.Add(new SimulatedUsbTmcDevice(new SimulatedInstrument(), 0x1234, 0x5678, "DOC1"));
            var usb = new ResourceManager(Options(o => { o.UsbBackend = backend; o.EnableUsb = true; }));
            cleanup.Add(usb);
            columns.Add(("USB INSTR", usb.Open("USB::0x1234::0x5678::DOC1::INSTR")));
            columns.Add(("USB RAW", usb.Open<VisaSession>("USB::0x1234::0x5678::DOC1::RAW")));

            var driver = new SimulatedGpibDriver();
            driver.Instruments[22] = new SimulatedInstrument();
            var gpib = new ResourceManager(Options(o => { o.GpibDriver = driver; o.EnableGpib = true; }));
            cleanup.Add(gpib);
            columns.Add(("GPIB INSTR", gpib.Open("GPIB0::22::INSTR")));
            columns.Add(("GPIB INTFC", gpib.Open<VisaSession>("GPIB0::INTFC")));

            if (OperatingSystem.IsLinux())
            {
                var pty = new PseudoTerminal();
                cleanup.Add(pty);
                var serial = new ResourceManager(Options(o => o.EnableSerial = true));
                cleanup.Add(serial);
                columns.Add(("ASRL INSTR", serial.Open($"ASRL{pty.SlavePath}::INSTR")));

                var pci = new FakePciFixture();
                cleanup.Add(pci);
                var pxi = pci.CreateResourceManager();
                cleanup.Add(pxi);
                columns.Add(("PXI INSTR", pxi.Open<VisaSession>(FakePciResource)));
            }

            File.WriteAllText(output, Render(columns));
        }
        finally
        {
            foreach (var (_, session) in columns) session.Dispose();
            for (int i = cleanup.Count - 1; i >= 0; i--) cleanup[i].Dispose();
        }
    }

    private const string FakePciResource = "PXI0::3-18.0::INSTR";

    private static ResourceManagerOptions Options(Action<ResourceManagerOptions> configure)
    {
        var options = new ResourceManagerOptions
        {
            EnableLanDiscovery = false,
            EnableMdnsDiscovery = false,
            EnableUsb = false,
            EnableSerial = false,
            EnableGpib = false,
            EnablePxi = false,
        };
        configure(options);
        return options;
    }

    /// <summary>The type of the value the first session that supports the attribute returns.</summary>
    private static string ValueTypeName(List<(string Title, VisaSession Session)> columns, VisaAttribute attribute)
    {
        var session = columns.First(c => c.Session.IsAttributeSupported(attribute)).Session;
        if (attribute is VisaAttribute.UserData or VisaAttribute.UserData32) return "object?";
        return session.GetAttribute(attribute) switch
        {
            null => "object?",
            bool => "bool",
            byte => "byte",
            short => "short",
            int => "int",
            long => "long",
            ulong => "ulong",
            string => "string",
            var v => v.GetType().Name,
        };
    }

    private static string Render(List<(string Title, VisaSession Session)> columns)
    {
        var all = columns.SelectMany(c => c.Session.SupportedAttributes).Distinct()
            .OrderBy(a => VisaAttributeNames.GetName(a), StringComparer.Ordinal).ToList();
        var text = new StringBuilder();
        text.AppendLine("# Attribute support by session type");
        text.AppendLine();
        text.AppendLine("<!-- Generated by tests/VisaCs.Tests/AttributeTableGenerator.cs. Regenerate on Linux with:");
        text.AppendLine("     VISACS_GENERATE_DOCS=$PWD/docs/attributes.md dotnet test tests/VisaCs.Tests --filter AttributeTableGenerator -->");
        text.AppendLine();
        text.AppendLine("This table is generated from live sessions opened against the simulators, so it lists exactly what");
        text.AppendLine("`GetAttribute`/`SetAttribute` accept. **RW** = read/write, **R** = read-only, blank = not supported");
        text.AppendLine("(`VI_ERROR_NSUP_ATTR`). **Type** is the type of the value `GetAttribute` returns; `SetAttribute` converts");
        text.AppendLine("other numeric types, and enum names, to it. Most attributes also have a typed property on the session class,");
        text.AppendLine("named in the IntelliSense documentation of the `VisaAttribute` member.");
        text.AppendLine();
        text.Append("| Attribute | Enum member | Type |");
        foreach (var (title, _) in columns) text.Append(' ').Append(title).Append(" |");
        text.AppendLine();
        text.Append("|---|---|---|");
        foreach (var _ in columns) text.Append(":-:|");
        text.AppendLine();
        foreach (var attribute in all)
        {
            text.Append("| `").Append(VisaAttributeNames.GetName(attribute)).Append("` | `").Append(attribute).Append("` |");
            text.Append(" `").Append(ValueTypeName(columns, attribute)).Append("` |");
            foreach (var (_, session) in columns)
            {
                string cell = !session.IsAttributeSupported(attribute) ? "" : session.IsAttributeWritable(attribute) ? "RW" : "R";
                text.Append(' ').Append(cell).Append(" |");
            }
            text.AppendLine();
        }
        text.AppendLine();
        text.AppendLine("## Events by session type");
        text.AppendLine();
        text.AppendLine("| Session | Events |");
        text.AppendLine("|---|---|");
        foreach (var (title, session) in columns)
        {
            var events = session.SupportedEventTypes.Select(e => $"`{e}`").ToList();
            text.Append("| ").Append(title).Append(" | ").Append(events.Count == 0 ? "none" : string.Join(", ", events)).AppendLine(" |");
        }
        text.AppendLine();
        text.Append("Columns: ");
        text.AppendLine(string.Join(", ", columns.Select(c => $"{c.Title} = `{c.Session.GetType().Name}`")) + ".");
        return text.ToString().Replace("\r\n", "\n");
    }

    private sealed unsafe partial class PseudoTerminal : IDisposable
    {
        private readonly int _master;

        public PseudoTerminal()
        {
            _master = posix_openpt(2 | 0x100);
            Assert.True(_master >= 0);
            Assert.Equal(0, grantpt(_master));
            Assert.Equal(0, unlockpt(_master));
            SlavePath = Marshal.PtrToStringUTF8(ptsname(_master))!;
        }

        public string SlavePath { get; }

        public void Dispose() => close(_master);

        [LibraryImport("libc.so.6", SetLastError = true)] private static partial int posix_openpt(int flags);
        [LibraryImport("libc.so.6", SetLastError = true)] private static partial int grantpt(int fd);
        [LibraryImport("libc.so.6", SetLastError = true)] private static partial int unlockpt(int fd);
        [LibraryImport("libc.so.6", SetLastError = true)] private static partial nint ptsname(int fd);
        [LibraryImport("libc.so.6", SetLastError = true)] private static partial int close(int fd);
    }
}
